mod models;

use std::fs::File;
use std::io::{BufReader, Read};
use models::NewEmployee;
use rust_decimal::dec;
use rust_decimal::Decimal;
use sqlx::raw_sql;
use sqlx::AssertSqlSafe;
use sqlx::postgres::PgPoolOptions;
use sqlx::PgPool;

fn read_sql_file() -> std::io::Result<String> {
    let file = File::open("employee.sql")?;
    let mut buf_reader = BufReader::new(file);
    let mut contents = String::new();
    buf_reader.read_to_string(&mut contents)?;
    Ok(contents)
}

fn sample_employees() -> Vec<NewEmployee> {
    vec![
        NewEmployee { name: "Alice".into(), age: Some(30), salary: dec!(85000.00), department: "Engineering".into() },
        NewEmployee { name: "Bob".into(), age: None, salary: dec!(62000.50), department: "Sales".into() },
        NewEmployee { name: "Carol".into(), age: Some(45), salary: dec!(120000.00), department: "Management".into() },
    ]
}

/// Inserts all employees in one transaction: either every row is saved or
/// none are. Returns the ids generated by the database.
async fn insert_employees(pool: &PgPool, employees: &[NewEmployee]) -> Result<Vec<i32>, sqlx::Error> {
    let mut tx = pool.begin().await?;
    let mut ids = Vec::with_capacity(employees.len());

    for e in employees {
        // $1..$4 are bind parameters: values are sent separately from the
        // SQL text, so there is no SQL injection risk.
        let id: i32 = sqlx::query_scalar(
            "INSERT INTO employees (name, age, salary, department)
             VALUES ($1, $2, $3, $4)
             RETURNING id",
        )
        .bind(&e.name)
        .bind(e.age) // None is sent as NULL
        .bind(e.salary)
        .bind(&e.department)
        .fetch_one(&mut *tx)
        .await?;
        ids.push(id);
    }

    tx.commit().await?;
    Ok(ids)
}

async fn print_employees(pool: &PgPool) -> Result<(), sqlx::Error> {
    let rows: Vec<(i32, String, Option<i32>, Decimal, String)> =
        sqlx::query_as("SELECT id, name, age, salary, department FROM employees ORDER BY id")
            .fetch_all(pool)
            .await?;

    println!("{:<4} {:<10} {:<5} {:>12} {}", "id", "name", "age", "salary", "department");
    for (id, name, age, salary, department) in rows {
        let age = age.map_or("-".to_string(), |a| a.to_string());
        println!("{id:<4} {name:<10} {age:<5} {salary:>12} {department}");
    }
    Ok(())
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    // Read SQL from the file
    let contents = read_sql_file()?;

    println!("File contents: {}", contents);

    // Connect to PostgreSQL
    let pool = PgPoolOptions::new()
        .max_connections(50)
        .connect("postgres://employee:employee@localhost:5432/employee_db")
        .await?;

    // Execute the SQL query from the file
    raw_sql(AssertSqlSafe(contents))
    .execute(&pool)
    .await?;

    println!("SQL executed successfully!");

    // Insert sample records
    let ids = insert_employees(&pool, &sample_employees()).await?;
    println!("Inserted {} employees with ids {:?}", ids.len(), ids);

    print_employees(&pool).await?;

    Ok(())
}
